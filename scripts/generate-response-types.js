'use strict';
const fs = require('fs');
const path = require('path');
const pb = require('protobufjs');
const root = new pb.Root();
root.resolvePath = (_, file) =>
	path.join(
		__dirname,
		'../protobufs',
		path.basename(file) === 'descriptor.proto' ? 'google/protobuf/descriptor.proto' : path.basename(file)
	);
root.loadSync(['cstrike15_gcmessages.proto', 'gcsdk_gcmessages.proto'], { keepCase: true }).resolveAll();
const roots = [
	'CMsgConnectionStatus',
	'CMsgGCCStrike15_v2_MatchmakingGC2ClientHello',
	'CMsgGCCStrike15_v2_MatchList',
	'CMsgGCCStrike15_v2_GC2ClientNotifyXPShop',
	'CMsgRecurringMissionSchema',
	'CMsgGCCStrike15_v2_PremierSeasonSummary',
	'CMsgGCCStrike15_v2_MatchmakingGC2ClientSearchStats'
];
const seen = new Map();
const name = (type) => type.fullName.slice(1).replace(/\./g, '_');
function visit(type) {
	if (seen.has(name(type))) return;
	seen.set(name(type), type);
	for (const field of type.fieldsArray) if (field.resolvedType instanceof pb.Type) visit(field.resolvedType);
}
roots.forEach((n) => visit(root.lookupType(n)));
let out =
	'// Generated by scripts/generate-response-types.js from the checked-in protocol snapshot.\n// Matches lib/proto-decode: uint64 strings, absent scalars/messages null, repeated fields arrays.\n';
for (const [n, type] of seen) {
	out += `export interface ${n} {\n`;
	for (const f of type.fieldsArray) {
		const t =
			f.resolvedType instanceof pb.Type
				? name(f.resolvedType)
				: f.resolvedType instanceof pb.Enum
					? 'number'
					: /64$/.test(f.type)
						? 'string'
						: f.type === 'bytes'
							? 'Uint8Array'
							: f.type === 'bool'
								? 'boolean'
								: f.type === 'string'
									? 'string'
									: 'number';
		out += `\t${f.name}: ${t}${f.repeated ? '[]' : ' | null'};\n`;
	}
	out += '}\n';
}
fs.writeFileSync(path.join(__dirname, '../types/responses.d.ts'), out);
